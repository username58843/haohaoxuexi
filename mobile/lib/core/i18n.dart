import 'package:flutter_riverpod/flutter_riverpod.dart';

import 'providers.dart';

/// Lightweight i18n, mirroring the web `t('key', 'English default')` pattern.
///
/// Usage:
/// ```dart
/// Text(tr(context, 'nav.home', 'Home'))
/// ```
/// The first argument (a BuildContext or a WidgetRef/Ref) is accepted for
/// call-site convention but the current language is read from a static holder
/// that [settingsProvider] keeps in sync. Widgets that render translated
/// strings should `ref.watch(languageProvider)` so they rebuild when the
/// language changes.
///
/// Adding strings: pass the English default inline and add matching entries to
/// the `ru` map below (mandatory) and `tk`/`zh` (best-effort).
class I18n {
  I18n._();

  static const List<String> supported = ['en', 'ru', 'tk', 'zh'];

  static String _language = 'en';

  static String get language => _language;

  /// Called by the settings notifier whenever the UI language changes.
  static void setLanguage(String lang) {
    _language = supported.contains(lang) ? lang : 'en';
  }
}

/// Current UI language code ('en' | 'ru' | 'tk' | 'zh').
/// Watch this in widgets that display translated strings.
final languageProvider = Provider<String>(
  (ref) => ref.watch(settingsProvider.select((s) => s.language)),
);

/// Translate [key], falling back to [enDefault].
/// [contextOrRef] may be a BuildContext, WidgetRef or Ref — it is accepted for
/// uniform call sites; the language itself comes from [I18n.language].
String tr(Object? contextOrRef, String key, String enDefault) {
  final lang = I18n.language;
  if (lang == 'en') return enDefault;
  return _overrides[lang]?[key] ?? enDefault;
}

